# Vesper Hub - regenerate PROVENANCE.md
# Records build id, date, commit, catalog totals and sha256 of every published file.
import hashlib, json, subprocess, time
from pathlib import Path

ROOT = Path(__file__).parent
CATALOG = ROOT / "catalog"
OUT = ROOT / "PROVENANCE.md"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def git(args):
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                              timeout=30).stdout.strip()
    except Exception:
        return ""


def main():
    index = json.loads((CATALOG / "index.json").read_text(encoding="utf-8"))
    catalog = json.loads((CATALOG / "catalog.json").read_text(encoding="utf-8"))

    games = catalog["games"]
    nk = sum(len(g.get("noKey") or []) for g in games.values())
    kk = sum(len(g.get("key") or []) for g in games.values())
    full = sum(1 for g in games.values() if len(g.get("noKey") or []) >= 4 and len(g.get("key") or []) >= 4)

    games_dir = CATALOG / "games"
    files = sorted(games_dir.glob("*.json"))
    combined = hashlib.sha256()
    total = 0
    for f in files:
        combined.update(f.name.encode())
        combined.update(f.read_bytes())
        total += f.stat().st_size

    commit = git(["rev-parse", "--short", "HEAD"]) or "uncommitted"
    branch = git(["rev-parse", "--abbrev-ref", "HEAD"]) or "main"
    remote = git(["remote", "get-url", "origin"]) or "https://github.com/Siidodirnfb/Vesper-Hub"

    lines = [
        "# Provenance",
        "",
        "This file is generated by `python provenance.py`. It records what was published,",
        "when, from which commit, and the exact bytes of each file.",
        "",
        f"- build id: `{index.get('build')}`",
        f"- generated: {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime(index.get('generated', time.time())))}",
        f"- build commit: `{commit}` on `{branch}`",
        f"- repository: {remote}",
        "",
        "The build commit is the one that carries the files hashed below. This file is",
        "committed immediately after it, so it can never contain its own hash.",
        "",
        "## Catalog",
        "",
        "| metric | value |",
        "| --- | --- |",
        f"| games | {index.get('count')} |",
        f"| keyless scripts | {nk} |",
        f"| key-locked scripts | {kk} |",
        f"| games with 4 keyless and 4 key-locked | {full} |",
        f"| sources | rscripts.net, scriptblox.com |",
        "",
        "## File hashes (sha256)",
        "",
        "| file | bytes | sha256 |",
        "| --- | --- | --- |",
    ]
    for rel in ("Vesper.lua", "catalog/index.json", "catalog/catalog.json"):
        p = ROOT / rel
        if p.exists():
            lines.append(f"| `{rel}` | {p.stat().st_size} | `{sha256(p)}` |")
    lines.append(f"| `catalog/games/*.json` ({len(files)} files) | {total} | `{combined.hexdigest()}` |")
    lines += [
        "",
        "Verify with `python verify.py`. A published copy whose hashes differ was either",
        "rebuilt by someone else or altered after publication.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"[done] wrote {OUT.name} for build {index.get('build')}")
    for line in lines[6:12]:
        print("  " + line)


if __name__ == "__main__":
    main()
